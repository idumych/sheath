#!/usr/bin/env python3
"""Writes Sheath's vector icon (Haiku HVIF) into src/ui/Sheath.rdef (between the markers).

HVIF layout: 'ncif', styles, paths, shapes. Coordinates are in a 64x64 box; a coordinate
is one byte (value + 32) when it is a whole number in -32..95, else two bytes.
"""
import os

STYLE_SOLID = 1		# RGBA
PATH_CLOSED = 1 << 1
PATH_NO_CURVES = 1 << 3
SHAPE_PATH_SOURCE = 10

styles = [
	(0xF4, 0xEC, 0xD6, 0xFF),	# 0 pages
	(0x7A, 0x2E, 0x1E, 0xFF),	# 1 cover
	(0x55, 0x1C, 0x12, 0xFF),	# 2 spine
	(0xE2, 0xB3, 0x48, 0xFF),	# 3 gold
	(0x30, 0x10, 0x0A, 0x60),	# 4 shadow
	(0xC9, 0xBF, 0xA4, 0xFF),	# 5 page edge lines
]

def rect(x0, y0, x1, y1):
	return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]

paths = [
	rect(14, 10, 57, 61),		# 0 shadow
	rect(14, 8, 55, 58),		# 1 pages
	rect(9, 4, 50, 56),			# 2 cover
	rect(9, 4, 15, 56),			# 3 spine
	rect(28, 15, 33, 45),		# 4 cross, upright
	rect(21, 23, 40, 28),		# 5 cross, beam
	rect(50, 12, 55, 13),		# 6 page lines
	rect(50, 20, 55, 21),
	rect(50, 28, 55, 29),
	rect(50, 36, 55, 37),
	rect(50, 44, 55, 45),
]

shapes = [  # (style, [paths])
	(4, [0]), (0, [1]), (5, [6, 7, 8, 9, 10]), (1, [2]), (2, [3]), (3, [4, 5]),
]

def coord(v):
	if float(v).is_integer() and -32 <= v <= 95:
		return bytes([int(v) + 32])
	raw = int(round((v + 128.0) * 102.0))
	return bytes([0x80 | (raw >> 8), raw & 0xFF])

out = bytearray(b"ncif")
out.append(len(styles))
for rgba in styles:
	out.append(STYLE_SOLID)
	out += bytes(rgba)
out.append(len(paths))
for pts in paths:
	out.append(PATH_CLOSED | PATH_NO_CURVES)
	out.append(len(pts))
	for x, y in pts:
		out += coord(x) + coord(y)
out.append(len(shapes))
for style, ps in shapes:
	out.append(SHAPE_PATH_SOURCE)
	out.append(style)
	out.append(len(ps))
	out += bytes(ps)
	out.append(0)		# no transform, no hinting

hexs = out.hex().upper()
lines = [hexs[i:i + 64] for i in range(0, len(hexs), 64)]
body = "\n".join('\t$"%s"' % l for l in lines)
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rdef = os.path.join(root, "src", "ui", "Sheath.rdef")
BEGIN = "// icon: generated by tools/make-icon.py\n"
END = "// end icon\n"
text = open(rdef).read()
if BEGIN in text:
	text = text[:text.index(BEGIN)] + text[text.index(END) + len(END):]
text = text.rstrip("\n") + "\n\n" + BEGIN + "resource vector_icon array {\n%s\n};\n" % body + END
open(rdef, "w").write(text)
print("icon: %d bytes of HVIF in src/ui/Sheath.rdef" % len(out))
